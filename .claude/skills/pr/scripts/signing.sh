#!/usr/bin/env bash
# SSH signing and verification shared with the unattended commit entry point.

export LC_ALL=C
set -o pipefail

dt_signing_key() {
  local key
  key=$(git config --get user.signingkey) || return 1
  case $key in
  key::*) key=${key#key::} ;;
  ssh-* | ecdsa-* | sk-*) ;;
  *)
    key=$(dt_path "$key") || return $?
    case $key in *.pub) ;; *) key=$key.pub ;; esac
    [ -f "$key" ] || return 1
    key=$(head -n 1 "$key") || return $?
    ;;
  esac
  printf '%s\n' "$key" | awk 'NF >= 2 { print $1, $2 }'
}

dt_agent_signing() {
  local format dir hook hooks marker
  format=$(git config --get gpg.format || true)
  [ "$format" = ssh ] || dt_die "Unattended commits require gpg.format=ssh."
  DT_SIGNING_KEY=$(dt_signing_key) || dt_die "user.signingkey must name a readable public key."
  [ -n "$DT_SIGNING_KEY" ] || dt_die "user.signingkey must name a public key."
  hooks=$(dt_repo_conf required_hooks 'commit-msg pre-commit post-commit') || return $?
  marker=$(dt_repo_conf hook_marker 'File generated by prek') || return $?
  [ -n "$hooks" ] && [ -n "$marker" ] || dt_die "required_hooks and hook_marker must not be empty."
  dir=$(gitr rev-parse --git-path hooks) || return $?
  for hook in $hooks; do
    case $hook in commit-msg | pre-commit | post-commit | prepare-commit-msg) ;;
    *) dt_die "Unknown required hook: $hook" ;;
    esac
    if [ ! -x "$dir/$hook" ] || ! grep -qF -- "$marker" "$dir/$hook"; then
      dt_die "Required hook is missing or has the wrong marker: $hook"
    fi
  done
}

# Snapshot immediately before git commit; hooks can move HEAD afterwards.
dt_agent_before_commit() {
  DT_COMMIT_REF=$2
  DT_COMMIT_TEXT=$(git stripspace <"$1") || return $?
  local ref
  ref=$(gitr symbolic-ref --quiet HEAD) || return $?
  [ "$ref" = "$DT_COMMIT_REF" ] || dt_die "The branch changed during the commit gates. Run the workflow again."
  DT_COMMIT_LOG_SIZE=$(gitr log -g --format=%H "$DT_COMMIT_REF" | wc -l) || return $?
}

# Verify the object created by this invocation, not a hook's replacement.
# On failure leave the evidence intact. Never rewrite an uncertain branch.
dt_agent_verify_commit() {
  local start=$1 tree=$2 mode=$3 state=$4
  local entries made tip parents expected actual_text live_ref why=''
  entries=$(gitr log -g --format=%H "$DT_COMMIT_REF" | wc -l) || return $?
  entries=$((entries - DT_COMMIT_LOG_SIZE))
  made=$(gitr log -g --format='%H %gs' "$DT_COMMIT_REF" |
    sed -n "1,${entries}p" | awk '/^[0-9a-f]+ commit( \(amend\))?: / { made=$1 } END { print made }') || return $?
  [ "$entries" -gt 0 ] && [ -n "$made" ] || dt_die "BLOCKED: cannot identify this invocation's commit. Inspect the branch history."
  tip=$(gitr rev-parse "$DT_COMMIT_REF") || return $?
  live_ref=$(gitr symbolic-ref --quiet HEAD || true)
  expected=$start
  if [ "$mode" = amend ]; then
    expected=$(gitr rev-list --parents -n 1 "$start" | cut -s -d' ' -f2-) || return $?
  elif [ "$start" = unborn ]; then
    expected=''
  fi
  parents=$(gitr rev-list --parents -n 1 "$made" | cut -s -d' ' -f2-) || return $?
  actual_text=$(gitr cat-file commit "$made" | sed '1,/^$/d' | git stripspace) || return $?
  printf 'agent-commit %s\n' "$DT_SIGNING_KEY" >"$state/commit.signers"
  if [ "$tip" != "$made" ] || [ "$live_ref" != "$DT_COMMIT_REF" ]; then
    why='a hook moved the branch or HEAD'
  elif [ "$parents" != "$expected" ]; then
    why='the parents differ from the reviewed parents'
  elif [ "$actual_text" != "$DT_COMMIT_TEXT" ]; then
    why='the message differs from the reviewed message'
  elif ! git -c gpg.ssh.program=ssh-keygen -c gpg.ssh.allowedSignersFile="$state/commit.signers" verify-commit "$made"; then
    why='the commit has no valid signature from the configured key'
  fi
  local actual_tree
  actual_tree=$(gitr rev-parse "$made^{tree}") || return $?
  [ "$actual_tree" = "$tree" ] || why='the tree differs from the reviewed tree'
  if [ -n "$why" ]; then
    printf 'BLOCKED: commit %s failed verification: %s. The commit and review evidence remain for recovery. A hook may already have pushed it.\n' "$made" "$why" >&2
    return 1
  fi
  printf 'committed: %s\n' "$made"
}
